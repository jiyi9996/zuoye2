/* USER CODE BEGIN 0 */
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
	static uint32_t last_tick=0;//最后一次改变的时间
	static uint8_t first_press=1;//判断是否第一次按下
	static uint8_t pressed=0;//判断是否持续按压
	if(GPIO_Pin!=GPIO_PIN_0)
	{
		return;
	}//只存在一个按键时，可不加
	uint32_t now=tim2_ms;
	if(!first_press&&(uint32_t)(now-last_tick)<20)//消抖
	{
		return;
	}
	first_press=0;//已经按了第一次
	last_tick=now;
	if(HAL_GPIO_ReadPin(GPIOA,GPIO_PIN_0)==GPIO_PIN_SET)//判断PA0引脚是否为高电平，高电平则为松手，则进入循环,开始判断按了多少秒
	{
		if((now-press_start)>=1000)//进入或退出快闪阶段
		{
				if(led_mode==2)//退出
				{
					led_mode=led_mode0;
				}
				else//进入
				{
					led_mode0=led_mode;
					led_mode=2;
				}
		}
		else//快闪时不变，常亮或者常灭时反转
		{
			if(led_mode!=2)
			{
				led_mode=!led_mode;
			}
		}
		pressed=0;
		return;
	}
	if(pressed)//按下之后不松手，且抖动结束
	{
		return;
	}
	pressed=1;
	press_start=tim2_ms;//按按键的起始时间
	//led_mode=!led_mode;
}

